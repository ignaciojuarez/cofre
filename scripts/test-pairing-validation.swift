import Foundation

// Unit test script for Cofre PairingFileValidator
func assertThrows<T>(_ expression: @autoclosure () throws -> T, verify: (Error) -> Void) {
    do {
        _ = try expression()
        print("FAIL: Expected error but succeeded")
        exit(1)
    } catch {
        verify(error)
    }
}

func assertNoThrow<T>(_ expression: @autoclosure () throws -> T) -> T {
    do {
        return try expression()
    } catch {
        print("FAIL: Unexpected error: \(error)")
        exit(1)
    }
}

func assertEqual<T: Equatable>(_ a: T, _ b: T) {
    if a != b {
        print("FAIL: \(a) != \(b)")
        exit(1)
    }
}

print("=== Running Cofre Pairing Validation Tests ===")

// 1. Rejects Non-Dictionary
let arrayData = try! PropertyListSerialization.data(fromPropertyList: ["Item1", "Item2"], format: .xml, options: 0)
assertThrows(try PairingFileValidator.validate(arrayData)) { error in
    assertEqual(error as? PairingFileValidationError, .notDictionary)
}
print("✓ Rejects non-dictionary property lists")

// 2. Rejects Missing Keys
let incompleteDict: [String: Any] = [
    "HostID": "my-host-id",
    "SystemBUID": "my-buid"
]
let incompleteData = try! PropertyListSerialization.data(fromPropertyList: incompleteDict, format: .xml, options: 0)
assertThrows(try PairingFileValidator.validate(incompleteData)) { error in
    guard case .missing(let key) = error as? PairingFileValidationError else {
        print("FAIL: Expected missing key error, got \(error)")
        exit(1)
    }
    if !PairingFileValidator.requiredKeys.contains(key) {
        print("FAIL: Key \(key) not in requiredKeys")
        exit(1)
    }
}
print("✓ Rejects plists missing required keys (HostID, SystemBUID, RootCertificate, HostCertificate, HostPrivateKey)")

// 3. Rejects Wrong Types
let wrongTypeDict: [String: Any] = [
    "HostID": "my-host-id",
    "SystemBUID": "my-buid",
    "HostCertificate": "not-data-a-string",
    "HostPrivateKey": Data([0x01, 0x02]),
    "RootCertificate": Data([0x03, 0x04])
]
let wrongTypeData = try! PropertyListSerialization.data(fromPropertyList: wrongTypeDict, format: .xml, options: 0)
assertThrows(try PairingFileValidator.validate(wrongTypeData)) { error in
    assertEqual(error as? PairingFileValidationError, .wrongType("HostCertificate"))
}
print("✓ Rejects plists with invalid data types for cryptographic certificates")

// 4. Accepts Valid Pairing File and Extracts UDID
let validDict: [String: Any] = [
    "HostID": "my-host-id",
    "SystemBUID": "my-buid",
    "HostCertificate": Data([0xAA, 0xBB]),
    "HostPrivateKey": Data([0xCC, 0xDD]),
    "RootCertificate": Data([0xEE, 0xFF]),
    "UDID": "OLD_DEVICE_UDID"
]
let validData = try! PropertyListSerialization.data(fromPropertyList: validDict, format: .xml, options: 0)
let extractedUDID = assertNoThrow(try PairingFileValidator.validate(validData))
assertEqual(extractedUDID, "OLD_DEVICE_UDID")
print("✓ Accepts valid pairing file and safely extracts UDID")

// 5. Test against simulated pairing file generated by llave-pair
let simPath = "/tmp/test-pair.mobiledevicepairing"
if FileManager.default.fileExists(atPath: simPath) {
    let simData = try! Data(contentsOf: URL(fileURLWithPath: simPath))
    let simUDID = assertNoThrow(try PairingFileValidator.validate(simData))
    assertEqual(simUDID, "00008150-SIMULATED-DEV")
    print("✓ Validates live simulated pairing file output from llave-pair CLI")
}

print("=== All Cofre Pairing Tests Passed! ===")
